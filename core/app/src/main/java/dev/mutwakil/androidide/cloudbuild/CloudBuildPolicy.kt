package dev.mutwakil.androidide.cloudbuild

internal object CloudBuildPolicy {
    const val WORKFLOW_PATH = ".github/workflows/mstudio-cloud-build.yml"
    const val WORKFLOW_ID = "mstudio-cloud-build.yml"

    fun detectTask(paths: Set<String>): String? {
        if ("gradlew" !in paths || paths.none { it == "settings.gradle" || it == "settings.gradle.kts" }) return null
        if ("app/build.gradle" in paths || "app/build.gradle.kts" in paths) return ":app:assembleDebug"

        val androidModules = paths.asSequence()
            .filter { it.endsWith("/src/main/AndroidManifest.xml") }
            .map { it.removeSuffix("/src/main/AndroidManifest.xml") }
            .filter { module ->
                "$module/build.gradle" in paths || "$module/build.gradle.kts" in paths
            }
            .sorted()
            .firstOrNull()

        if (androidModules != null) {
            return ":" + androidModules.replace("/", ":") + ":assembleDebug"
        }
        if ("build.gradle" in paths || "build.gradle.kts" in paths) return "assembleDebug"
        return null
    }

    fun isSafeGradleTask(task: String): Boolean =
        task.matches(Regex("^(assemble(Debug|Release)|:[A-Za-z0-9_.:-]+:assemble(Debug|Release))$")) &&
            !task.contains("..") && !task.contains(';') && !task.contains('\n') && !task.contains('\r')

    fun workflow(task: String, javaVersion: String): String {
        require(isSafeGradleTask(task)) { "Unsupported Gradle task" }
        require(javaVersion == "17" || javaVersion == "21") { "Unsupported Java version" }
        return """# Generated by MStudio after explicit user approval.
# This workflow executes Gradle scripts from the selected repository on GitHub-hosted runners.
name: MStudio Cloud Build

on:
  workflow_dispatch:

permissions:
  contents: read

concurrency:
  group: mstudio-cloud-build-${'$'}{{ github.ref }}
  cancel-in-progress: false

jobs:
  build:
    runs-on: ubuntu-latest
    timeout-minutes: 45
    permissions:
      contents: read
    steps:
      - name: Checkout selected source ref
        uses: actions/checkout@11bd71901bbe5b1630ceea73d27597364c9af683
        with:
          ref: ${'$'}{{ github.ref }}
          persist-credentials: false

      - name: Set up JDK $javaVersion
        uses: actions/setup-java@dded0888837ed1f317902acf8a20df0ad188d165
        with:
          distribution: temurin
          java-version: '$javaVersion'
          cache: gradle

      - name: Validate Gradle wrapper
        shell: bash
        run: |
          test -f ./gradlew
          test -f ./gradle/wrapper/gradle-wrapper.jar
          test -f ./gradle/wrapper/gradle-wrapper.properties
          chmod +x ./gradlew
          grep -Eq '^distributionUrl=https://services\.gradle\.org/distributions/gradle-[^[:space:]]+\.zip$' gradle/wrapper/gradle-wrapper.properties

      - name: Build debug APK
        shell: bash
        run: ./gradlew '$task' --no-daemon --stacktrace

      - name: Collect APKs
        shell: bash
        run: |
          mkdir -p cloud-build-apks
          find . -type f -path '*/build/outputs/apk/*/*.apk' -not -path '*/build/intermediates/*' -print0 |
            while IFS= read -r -d '' file; do cp "$file" cloud-build-apks/; done
          test -n "$(find cloud-build-apks -maxdepth 1 -type f -name '*.apk' -print -quit)"

      - name: Upload APK artifact
        uses: actions/upload-artifact@ea165f8d65b6e75b540449e92b4886f43607fa02
        with:
          name: mstudio-apk-${'$'}{{ github.run_id }}
          path: cloud-build-apks/*.apk
          if-no-files-found: error
          retention-days: 7
"""
    }
}
